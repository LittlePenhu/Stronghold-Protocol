#!/usr/bin/env node
// tools/preload.mjs — the `<link rel="modulepreload">` list of public/index.html, from the static import graph of
// public/js/main.js.
//
// The page is a no-build ES-module graph: the browser fetches /js/main.js, parses it, discovers its imports, fetches
// those, and so on — 7 layers and 164 modules before the title screen has everything it imports. Every one of them is a
// STATIC import of the entry, so the page needs it before its first frame anyway; without the list each layer waits for
// the one above it (a 7-round-trip waterfall on a high-latency link). `rel="modulepreload"` starts the whole graph in
// the first round trip; the bytes are the same, and the list costs ~9 KB of HTML (≈2 KB compressed).
//
//   * static only: `import './x.js'`, `import … from`, `export … from` — a dynamic `import()` is lazy by design and
//     stays out (the 3D board's three.js and the battlefield's pixi are loaded when a view needs them).
//   * the served URL of a file: public/ → /, shared/ → /shared/, server/sim/ → /sim/ (the mounts of http/static.js).
//
// Usage:  node tools/preload.mjs           rewrite the block in public/index.html (npm run preload)
//         node tools/preload.mjs --check   exit 1 when the block is stale, print the difference (test/preload.test.js)
// The block between the two markers below is generated — do not edit its lines by hand.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const PAGE = join(ROOT, 'public', 'index.html');
export const ENTRY = join(ROOT, 'public', 'js', 'main.js');
/** The block's boundaries in public/index.html. */
export const MARKER_START = '<!-- modulepreload: generated by tools/preload.mjs from the static import graph of public/js/main.js (npm run preload); do not edit by hand -->';
export const MARKER_END = '<!-- /modulepreload -->';

/** The mounts http/static.js serves, longest prefix first. */
const MOUNTS = Object.freeze([['server/sim/', '/sim/'], ['public/', '/'], ['shared/', '/shared/']]);

/** The served URL of an absolute file path; null when the path is not under a served mount. */
export function urlOf(file, root = ROOT) {
  const rel = relative(root, file).split(sep).join('/');
  for (const [dir, url] of MOUNTS) if (rel.startsWith(dir)) return url + rel.slice(dir.length);
  return null;
}

/**
 * The specifiers a module statically imports (`import … from 'x'`, `import 'x'`, `export … from 'x'`) — not `import()`,
 * not a comment or a string that merely looks like one (the regexes only match at the start of a line: the repository's
 * style puts imports there, see CONTRIBUTING).
 * @param {string} src
 * @returns {string[]}
 */
export function staticSpecifiers(src) {
  const out = [];
  const from = /(?:^|\n)[ \t]*(?:import|export)\b[^'"`;]*?\bfrom\s*['"]([^'"]+)['"]/g;
  const bare = /(?:^|\n)[ \t]*import\s*['"]([^'"]+)['"]/g;
  for (const re of [from, bare]) {
    for (const m of src.matchAll(re)) if (!out.includes(m[1])) out.push(m[1]);
  }
  return out;
}

/**
 * The static import graph of `entry`, breadth first, each layer in specifier order (deterministic). Files that do not
 * exist are an error: they mean `npm install` has not run (`public/vendor` is generated by its postinstall).
 * @param {string} [entry]
 * @param {{ read?: (file: string) => string }} [opts]
 * @returns {{ file: string, url: string, depth: number }[]}
 */
export function staticGraph(entry = ENTRY, { read = (file) => readFileSync(file, 'utf8') } = {}) {
  /** @type {{ file: string, url: string, depth: number }[]} */
  const out = [];
  const seen = new Set();
  const add = (file, depth) => {
    const url = urlOf(file);
    if (!url) return;
    if (!existsSync(file)) throw new Error(`preload: ${relative(ROOT, file)} does not exist (run npm install first)`);
    seen.add(file);
    out.push({ file, url, depth });
  };
  add(entry, 0);
  for (let i = 0; i < out.length; i++) {
    const { file, depth } = out[i];
    for (const spec of staticSpecifiers(read(file))) {
      if (!spec.startsWith('.')) continue; // bare specifiers are import-map entries (never inside public/js)
      const target = resolve(dirname(file), spec);
      if (!seen.has(target)) add(target, depth + 1);
    }
  }
  return out;
}

/** The `<link>` lines of a graph, in graph order (entry first, then modulepreload of every depth). */
export function preloadLines(graph) {
  return graph.map(({ url }) => `  <link rel="modulepreload" href="${url}" />`);
}

/** The whole block, markers included (what public/index.html holds between and including them). */
export function preloadBlock(graph) {
  return [MARKER_START, ...preloadLines(graph), MARKER_END].join('\n');
}

/** Replace the block in `html`; a document without the markers is an error (the anchors are part of the page). */
export function withPreloadBlock(html, graph) {
  const a = html.indexOf(MARKER_START);
  const b = html.indexOf(MARKER_END);
  if (a < 0 || b < 0 || b < a) throw new Error('preload: the markers are missing from public/index.html');
  return html.slice(0, a) + preloadBlock(graph) + html.slice(b + MARKER_END.length);
}

/**
 * The block as it is in `html`, without the markers.
 * @param {string} html
 * @returns {string[]}
 */
export function blockLines(html) {
  const a = html.indexOf(MARKER_START);
  const b = html.indexOf(MARKER_END);
  if (a < 0 || b < 0 || b < a) return [];
  return html.slice(a + MARKER_START.length, b).split('\n').map((l) => l.trim()).filter(Boolean);
}

function main(argv) {
  const check = argv.includes('--check');
  const graph = staticGraph();
  const html = readFileSync(PAGE, 'utf8');
  const next = withPreloadBlock(html, graph);
  if (next === html) {
    console.log(`preload: up to date (${graph.length} modules)`);
    return 0;
  }
  if (check) {
    console.error(`preload: public/index.html is stale (${graph.length} modules; run npm run preload)`);
    return 1;
  }
  writeFileSync(PAGE, next);
  console.log(`preload: wrote ${graph.length} modules to public/index.html`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
