// tools/preload.mjs and the generated `modulepreload` block of public/index.html: the page is a no-build ES-module
// graph, so the block is what keeps the browser from discovering its 7 layers one round trip at a time. This suite is
// the drift gate: change an import in public/js/ (or shared/) and the block must be regenerated with `npm run preload`.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PAGE, blockLines, preloadLines, staticGraph, staticSpecifiers, withPreloadBlock } from '../tools/preload.mjs';

test('public/index.html preloads the whole static graph of the entry, in graph order', () => {
  const html = readFileSync(PAGE, 'utf8');
  const graph = staticGraph();
  assert.ok(graph.length > 120, `only ${graph.length} modules in the graph (a public/js file failing to parse?)`);
  assert.deepEqual(blockLines(html), preloadLines(graph).map((l) => l.trim()), 'the block is stale: run npm run preload');
  assert.equal(withPreloadBlock(html, graph), html, 'tools/preload.mjs would rewrite the page');
  // the entry first, then layers: the page needs no module before the ones it imports
  assert.equal(graph[0].url, '/js/main.js');
  const depths = graph.map((g) => g.depth);
  assert.deepEqual(depths, [...depths].sort((a, b) => a - b), 'breadth first');
  assert.equal(new Set(graph.map((g) => g.url)).size, graph.length, 'one link per module');
  // the page still loads the entry itself as a module (the preload is not the loader)
  assert.match(html, /<script type="module" src="\/js\/main\.js"/);
  // and the vendor files the graph reaches are the import-map entries, not a CDN
  assert.ok(graph.some((g) => g.url === '/vendor/preact.module.js'));
  assert.ok(graph.every((g) => g.url.startsWith('/')));
});

test('staticSpecifiers: import / export … from / bare import, never a dynamic import() or a comment', () => {
  assert.deepEqual(
    staticSpecifiers("import a from './a.js';\nexport { b } from './b.js';\nimport './c.js';\n"),
    ['./a.js', './b.js', './c.js'],
  );
  assert.deepEqual(staticSpecifiers("const x = await import('./lazy.js');\n// import y from './comment.js'\n"), []);
});

test('withPreloadBlock replaces only the marked block and refuses a page without the markers', () => {
  const page = `<head>\n${'<!-- modulepreload: generated by tools/preload.mjs from the static import graph of public/js/main.js (npm run preload); do not edit by hand -->'}\n  <link rel="modulepreload" href="/js/main.js" />\n<!-- /modulepreload -->\n</head>`;
  const graph = [{ file: 'x', url: '/js/main.js', depth: 0 }];
  assert.equal(withPreloadBlock(page, graph), page);
  const stale = page.replace('<link rel="modulepreload" href="/js/main.js" />', '<link rel="modulepreload" href="/js/old.js" />');
  assert.match(withPreloadBlock(stale, graph), /href="\/js\/main\.js"/);
  assert.throws(() => withPreloadBlock('<head></head>', graph), /markers are missing/);
});
